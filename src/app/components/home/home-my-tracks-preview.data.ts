type PreviewCoordinate = [longitude: number, latitude: number];

function previewTrack(
  id: string,
  type: ActivityTypes,
  coordinates: PreviewCoordinate[],
): TracksMapPreparedTrack {
  return {
    activity: {
      getID: () => id,
      type,
    },
    coordinates,
  };
}

