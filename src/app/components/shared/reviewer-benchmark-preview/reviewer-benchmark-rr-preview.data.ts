export const REVIEWER_RR_BEATS: readonly RRAnalyzedBeat[] = EXCERPT.map(([time, interval, classification]) => ({
  time, interval, classification, segment: 0,
}));

// Full-recording values, verified against the original intervals. These are not
// recomputed from the short chart excerpt and are independent of agreement grades.
export const REVIEWER_RR_SUMMARY = {
  coveragePercentage: 99.9950223179678,
  artifactPercentage: 1.4975743514026576,
  rmssd: 8.063781172065804,
} as const;

export function buildReviewerRRMetricRows(settings?: UserUnitSettingsInterface) {
  return [
    { label: 'R–R coverage', type: DataRRCoverage.type, value: REVIEWER_RR_SUMMARY.coveragePercentage },
    { label: 'Artifacts', type: DataRRArtifactPercentage.type, value: REVIEWER_RR_SUMMARY.artifactPercentage },
    { label: 'RMSSD', type: DataRRRMSSD.type, value: REVIEWER_RR_SUMMARY.rmssd },
  ].map(metric => ({ label: metric.label, display: formatBenchmarkRRValue(metric.type, metric.value, settings)?.text ?? 'Unavailable' }));
}

export function buildReviewerRRChartOption(darkTheme: boolean, width: number) {
  const { rr } = buildBenchmarkRRChartOptions({
    recordings: [{ key: 'recorded-rr-sample', label: 'Recorded sample',
      analysis: { beats: [...REVIEWER_RR_BEATS], windows: [] },
      startTimeMs: 0, durationMs: REVIEWER_RR_EXCERPT_DURATION_MS,
      color: resolveDeviceChartColor(AppColors.Blue, darkTheme), lineStyle: 'solid' }],
    excludeFlagged: false, darkTheme,
    artifactColor: resolveDeviceChartColor(AppColors.Orange, darkTheme), width,
  });
  const xAxis = Array.isArray(rr.xAxis) ? rr.xAxis[0] : rr.xAxis;
  return { ...rr, animation: false, grid: { left: 52, right: 12, top: 26, bottom: 30 },
    xAxis: { ...xAxis, axisLabel: { ...xAxis?.axisLabel, formatter: (value: number) => formatDurationSeconds(value / 1000) } },
    dataZoom: [], tooltip: { show: false },
    series: (Array.isArray(rr.series) ? rr.series : []).map(series => ({ ...series, silent: true })),
  };
}
